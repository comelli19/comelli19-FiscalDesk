// Matriz oficial de alíquotas interestaduais do ICMS no Brasil (Art. 155 CF/88 e Res. Senado 22/89)
export function getAliquotaInterestadual(ufOrigem: string, ufDestino: string, isImportado: boolean = false): number {
  if (ufOrigem === ufDestino) {
    const uf = INITIAL_UFS.find((u) => u.sigla === ufOrigem);
    return uf ? uf.aliquotaInterna : 18.0;
  }
  
  // Resolução do Senado Federal nº 13/2012: produtos com Conteúdo de Importação > 40%
  if (isImportado) {
    return 4.0;
  }
  
  const sulSudesteSemES = ['SP', 'RJ', 'MG', 'PR', 'SC', 'RS'];
  const norteNordesteCentroOesteMaisES = [
    'AC', 'AL', 'AP', 'AM', 'BA', 'CE', 'DF', 'ES', 'GO', 'MA',
    'MT', 'MS', 'PA', 'PB', 'PE', 'PI', 'RN', 'RO', 'RR', 'SE', 'TO'
  ];

  if (sulSudesteSemES.includes(ufOrigem) && norteNordesteCentroOesteMaisES.includes(ufDestino)) {
    return 7.0;
  }

  return 12.0;
}
